"""Small deterministic factory bundler shared by page generators.

Source files each register one factory. No source evaluation or runtime import is
needed. Both the source declaration and manifest must describe the same DAG.
"""
from __future__ import annotations
import json
import re
from pathlib import Path

DECLARATION = re.compile(r"\bdefine\(\s*(['\"])([^'\"]+)\1\s*,\s*(\[[^\]]*\])\s*,\s*function\s*\(")


def validate_bundle(base_dir: str | Path, bundle: dict) -> list[dict]:
    base_dir = Path(base_dir)
    modules = bundle['modules']
    by_id = {}
    for module in modules:
        module_id = module['id']
        if module_id in by_id:
            raise ValueError(f'Duplicate module: {module_id}')
        source = (base_dir / module['source']).read_text(encoding='utf-8')
        declarations = list(DECLARATION.finditer(source))
        if len(declarations) != 1:
            raise ValueError(f'Expected one factory declaration: {module["source"]}')
        declaration = declarations[0]
        # Dependencies are restricted to quoted module ids; no executable values.
        raw = declaration.group(3)
        if re.sub(r"(['\"])[A-Za-z0-9_.-]+\1|[\[\],\s]", '', raw):
            raise ValueError(f'Invalid dependency list: {module_id}')
        declared = re.findall(r"['\"]([A-Za-z0-9_.-]+)['\"]", raw)
        if declaration.group(2) != module_id or declared != module['dependencies']:
            raise ValueError(f'Manifest and factory differ: {module_id}')
        if len(declared) != len(set(declared)):
            raise ValueError(f'Duplicate dependency: {module_id}')
        by_id[module_id] = module
    ordered, active, seen = [], [], set()

    def visit(module_id: str):
        if module_id not in by_id:
            raise ValueError(f'Missing module: {module_id}')
        if module_id in active:
            raise ValueError('Circular dependency: ' + ' -> '.join(active + [module_id]))
        if module_id in seen:
            return
        active.append(module_id)
        for dependency in by_id[module_id]['dependencies']:
            visit(dependency)
        active.pop()
        seen.add(module_id)
        ordered.append(by_id[module_id])

    visit(bundle['entry'])
    # Unused modules also have to satisfy the manifest contract.
    for module_id in sorted(by_id):
        visit(module_id)
    return ordered


def load_manifest(path: str | Path) -> dict:
    manifest = json.loads(Path(path).read_text(encoding='utf-8'))
    if manifest.get('version') != 1:
        raise ValueError('Unsupported bundle manifest version')
    outputs = [bundle['output'] for bundle in manifest['bundles']]
    if len(outputs) != len(set(outputs)):
        raise ValueError('Duplicate bundle output')
    return manifest


def build_bundle(base_dir: str | Path, bundle: dict) -> str:
    """Return standalone JS for a validated bundle, without writing files."""
    base_dir = Path(base_dir)
    runtime = Path(__file__).with_name('bundle_runtime.js').read_text(encoding='utf-8')
    modules = validate_bundle(base_dir, bundle)
    sources = [(base_dir / module['source']).read_text(encoding='utf-8').rstrip() for module in modules]
    namespace, entry = json.dumps(bundle['namespace']), json.dumps(bundle['entry'])
    return ('/* Generated by bundle_builder.py; edit factory sources, then regenerate. */\n'
            '(function () {\n  \'use strict\';\n' + runtime.rstrip() + '\n'
            '  var container = createModuleContainer();\n  var define = container.define;\n'
            + '\n\n'.join(sources) + '\n'
            + f'  window[{namespace}] = Object.freeze({{get: container.get}});\n'
            + f'  container.get({entry});\n' + '})();\n')
