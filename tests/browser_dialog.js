const { chromium } = require('playwright');
const assert = require('node:assert/strict');
(async () => {
 const browser = await chromium.launch({headless:true});
 const page = await browser.newPage({viewport:{width:1600,height:1000}});
 page.on('pageerror', error => console.error('PAGEERROR', error.message));
 await page.goto((process.env.E2E_SITE || 'http://127.0.0.1:8112') + '/learning-path.html?t=dialog-e2e-20260914');
 await page.locator('#node-n1').click();
 await page.locator('#node-n1 button[data-mat="quiz"]').click();
 console.log(await page.locator('#node-n1').innerText());
 await page.screenshot({path:'docs/verification/02-compact.png',fullPage:true});
 await page.getByRole('button',{name:'打开测验',exact:true}).click();
 await page.waitForSelector('#quiz-workspace .qd-question');
 assert.equal(await page.locator('#qd-round option').count(),2);
 await page.locator('#qd-answer-5').fill('新题草稿：控制变量');
 await page.locator('#qd-prev').click();
 await page.locator('#qd-answer-5').fill('旧题草稿：排除其他因素');
 await page.locator('#qd-close').click();
 await page.reload();
 await page.locator('#node-n1').click();
 await page.locator('#node-n1 button[data-mat="quiz"]').click();
 await page.getByRole('button',{name:'打开测验',exact:true}).click();
 await page.waitForSelector('#quiz-workspace .qd-question');
 assert.equal(await page.locator('#qd-answer-5').inputValue(),'新题草稿：控制变量');
 await page.locator('#qd-prev').click();
 assert.equal(await page.locator('#qd-answer-5').inputValue(),'旧题草稿：排除其他因素');
 await page.screenshot({path:'docs/verification/03-dialog.png'});
 await page.keyboard.press('Escape');
 assert.equal(await page.locator('#quiz-workspace').evaluate(el=>el.open),false);
 await page.goto((process.env.E2E_SITE || 'http://127.0.0.1:8112') + '/quiz-map.html?t=dialog-e2e-2');
 await page.getByRole('button',{name:'打开测验',exact:true}).click();
 await page.waitForSelector('#quiz-workspace .qd-question');
 assert.equal(await page.locator('#qd-round option').count(),2);
 await page.locator('#qd-answer-5').fill('综合新题草稿');
 await page.locator('#qd-prev').click();
 await page.locator('#qd-answer-5').fill('综合旧题草稿');
 await page.locator('#qd-next').click();
 assert.equal(await page.locator('#qd-answer-5').inputValue(),'综合新题草稿');
 console.log('PASS: compact cards, modal, drafts on close/reload, old/new paging, Esc, comprehensive history');
 await browser.close();
})().catch(error=>{console.error(error);process.exit(1)});
