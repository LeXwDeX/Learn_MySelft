"use strict";
const assert = require('assert');
const fs = require('fs');
const vm = require('vm');
function setup() {
  const elements = new Map();
  for (const id of ['lib-pop', 'lib-count', 'dm-topic', 'dm-err', 'dm-pass', 'del-modal', 'dm-ok', 'dm-cancel', 'lib-btn', 'lib-wrap']) elements.set(id, {innerHTML: '', textContent: '', value: '', hidden: true, open: false, focus() {}, addEventListener() {}});
  let library;
  const documentEvents = {};
  let focused = '';
  for (const [id, element] of elements) element.focus = () => {focused = id;};
  const persistence = {deleteState: () => Promise.resolve({ok: true})};
  const user = {readOnly: false, fetch: async () => { throw Error('offline'); }};
  const env = {window: {LearnUser: user, LearnTitles: {document: d => d.topic, quiz: d => ({title: d.title})}, LearnUI: {dialog: {open: d => {d.open = true;}, close: d => {d.open = false;}}}}, document: {activeElement: {focus() {}}, addEventListener: (name, fn) => {documentEvents[name] = fn;}}, location: {}, confirm: () => true,
    define(name, names, factory) { library = factory({'path.persistence': persistence, 'path.shell': {}, 'path.model': {session: {API: '', STORE_PREFIX: 'learn-path-v1-', USER_PATH: 'u/', STAGE_LABEL: {}}}, 'path.format': {$: id => elements.get(id), stripUser: key => key.replace(/^u\//, ''), esc: s => s, storeKey: () => 'other'}}); }};
  vm.runInNewContext(fs.readFileSync('learning-path/modules/path-library.js', 'utf8'), env);
  return {library, user, elements, persistence, documentEvents, focused: () => focused};
}
(async () => {
  const {library, user, elements, persistence, documentEvents, focused} = setup();
  await assert.rejects(library.fetchMaterials(), /offline/);
  await library.libRender();
  assert.match(elements.get('lib-pop').innerHTML, /重试/);
  let requests = [];
  user.fetch = () => new Promise(resolve => requests.push(resolve));
  const first = library.libRender(), second = library.libRender();
  assert.equal(requests.length, 2, 'One shared snapshot per rendering');
  requests[1]({ok: true, json: async () => ({entries: {'u/learn-path-v1-new': JSON.stringify({topic: 'new', plan: {nodes: [{id: 'a'}]}, nodeState: {a: {completed: true}, orphan: {completed: true}}})}})});
  await second;
  requests[0]({ok: true, json: async () => ({entries: {}})});
  await first;
  assert.match(elements.get('lib-pop').innerHTML, /new/);
  user.fetch = async () => ({ok: true, json: async () => ({entries: {'u/learn-path-v1-new': JSON.stringify({topic: 'new', plan: {nodes: [{id: 'a'}]}, nodeState: {a: {completed: true}, orphan: {completed: true}}})}})});
  assert.equal((await library.fetchMaterials())[0].done, 1);
  let finish, deletes = 0;
  persistence.deleteState = () => { deletes++; return new Promise(resolve => {finish = resolve;}); };
  library.openDelModal('old', 'old');
  elements.get('dm-pass').value = 'secret';
  const pending = library.submitDel();
  library.submitDel();
  await Promise.resolve();
  assert.equal(deletes, 1, 'Repeated confirmation must issue one deletion');
  assert.equal(elements.get('dm-cancel').disabled, true);
  library.closeDelModal();
  assert.equal(elements.get('del-modal').open, true, 'Pending deletion must remain visible');
  library.openDelModal('new', 'new');
  assert.equal(elements.get('dm-topic').textContent, 'old', 'Pending deletion cannot be replaced');
  library.libBind();
  elements.get('lib-pop').hidden = false;
  documentEvents.keydown({key: 'Escape'});
  assert.equal(elements.get('lib-pop').hidden, false, 'Dialog Escape must preserve library');
  finish({ok: true});
  await pending;
  assert.equal(elements.get('del-modal').open, false);
  assert.equal(elements.get('dm-pass').value, '');
  assert.equal(focused(), 'lib-btn', 'Successful list rebuild must restore a surviving control');
  documentEvents.keydown({key: 'Escape'});
  assert.equal(elements.get('lib-pop').hidden, true);
  assert.equal(focused(), 'lib-btn');
  library.openDelModal('new', 'new');
  persistence.deleteState = async () => ({ok: false, error: 'wrong password'});
  await library.submitDel();
  assert.equal(elements.get('dm-err').textContent, 'wrong password');
  assert.equal(elements.get('dm-ok').disabled, false, 'Failure must allow retry');
  assert.equal(elements.get('dm-cancel').disabled, false, 'Failure must allow cancellation');
  library.closeDelModal();
  user.readOnly = true;
  await library.libRender();
  assert(!elements.get('lib-pop').innerHTML.includes('lib-del'));
  assert(!elements.get('lib-pop').innerHTML.includes('?new=1'));
  library.openDelModal('new', 'new');
  assert.equal(elements.get('del-modal').open, false);
  console.log('path library recovery tests passed');
})().catch(error => {console.error(error); process.exitCode = 1;});
