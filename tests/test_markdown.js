'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const window={markdownit:require('../shared/vendor-markdown-it.js')};
vm.runInNewContext(fs.readFileSync('shared/markdown.js','utf8'),{window,WeakMap,Promise});
const md=window.LearnMarkdown;
assert.equal(md.normalizeMermaid('flowchart TD\n A["向量<br>与<BR />坐标<br/>表示"] --> B'), 'flowchart TD\n A["向量 与 坐标 表示"] --> B');
assert.equal(md.normalizeMermaid('flowchart TD\n A["坏<br onclick=x>标签"] --> B'), 'flowchart TD\n A["坏<br onclick=x>标签"] --> B');
assert.equal(md.normalizeMermaid('flowchart TD\n A<br/> --> B'), 'flowchart TD\n A<br/> --> B');
assert.equal(md.normalizeMermaid('flowchart TD\n A["引号\\"<br/>标签"] --> B'), 'flowchart TD\n A["引号\\" 标签"] --> B');
assert.match(md.render('| 比较 | 说明 |\n| --- | --- |\n| A | B |'),/<table>/);
assert.match(md.render('$\\|x\\|_2$'),/\\\|x\\\|_2/);
assert.doesNotMatch(md.render('<img src=x onerror=alert(1)>'),/<img/);
assert.doesNotMatch(md.render('[bad](javascript:alert(1))'),/href="javascript:/);
assert.doesNotMatch(md.render('![external](https://invalid.example/image.png)'),/<img/);
const graph='```mermaid\nflowchart TD\n A["条件"] --> B["结论"]\n```';
assert.match(md.render(graph),/data-diagram="pending"/);
assert.match(md.render(graph,{streaming:true}),/data-diagram="waiting"/);
assert.match(md.render(graph.slice(0,-3)),/data-diagram="invalid"/);
assert.match(md.render('~~~mermaid\nflowchart TD\n A-->B\n~~~'),/data-diagram="pending"/);
assert.match(md.render('```js\nconsole.log(1)\n```'),/language-js/);
const scene='```learn-scene\n{"version":1,"title":"<script>bad()</script>"}\n```';
assert.match(md.render(scene),/data-scene="pending"/);
assert.match(md.render(scene,{streaming:true}),/data-scene="waiting"/);
assert.match(md.render(scene.slice(0,-3)),/data-scene="invalid"/);
assert.match(md.render('~~~learn-scene\n{}\n~~~'),/data-scene="pending"/);
assert.match(md.render('````learn-scene\n{}\n````'),/data-scene="pending"/);
assert.match(md.render(scene),/&lt;script&gt;bad\(\)&lt;\/script&gt;/);
assert.doesNotMatch(md.render(scene),/<script>/);
assert.match(md.render('正文前\n\n'+scene+'\n\n正文后'),/<p>正文后<\/p>/);
console.log('Markdown parser contract passed');

const tail='两列完全相同，因此这个等价关系成立。';
const matrix='| p | q |\n| --- | --- |\n| T | F |\n'+tail+'\n说明文字仍然在表格外面。';
const fixed=md.render(matrix);
assert.equal((fixed.match(/<tr>/g)||[]).length,2);
assert.match(fixed,/<\/table>\s*<p>两列完全相同/);
assert.equal(matrix.split('\n').length,5, 'caller source stays unchanged');
assert.match(md.render('| 单列 |\n| --- |\n| T |\n'+tail),/<td>两列完全相同/, 'single-column rows stay rows');
assert.match(md.render('| a | b |\n|---|---|\n| A | B |\n备注'),/<td>备注/, 'ambiguous short sparse row stays a row');
assert.match(md.render('| a | b |\n|---|---|\n| A | B |\n| '+tail+' | |'),/<td>两列完全相同/, 'explicit sparse row stays a row');
assert.match(md.render('```text\n'+matrix+'\n```'),/\| T \| F \|/);
assert.match(md.render('| a | b |\n|---|---|\n| A | B |\n这个公式中有 $x\\|y$，不自动调整。'),/<td>这个公式/, 'literal pipe ambiguity stays untouched');
assert.match(md.render(matrix+'\n\n'+graph),/data-diagram="pending"/, 'table normalization keeps fence source maps aligned');
assert.match(md.render(matrix+'\n\n'+graph.slice(0,-3)),/data-diagram="invalid"/);
assert.match(md.render(matrix+'\n\n'+scene),/data-scene="pending"/, 'scene fences keep source maps after table normalization');
assert.doesNotThrow(()=>md.render(matrix,{streaming:true}));
console.log('PASS conservative table boundaries, sparse/single-column/code/math and fence maps');
assert.match(md.render('定义[^1]。\n\n[^1]: **补充**说明\n    继续说明'), /补充说明〔1〕.*<strong>补充<\/strong>说明/);
assert.match(md.render('> [!WARNING]\n> 注意符号。'), /易错提醒/);
assert.match(md.render('```text\n[^1]: 原样\n> [!NOTE]\n```'), /\[\^1\]: 原样/);
assert.match(md.render('$\\badcommand{x}$'), /md-math-fallback/);
assert.equal(md.unitFilename('命题逻辑与有效推理',1,'命题、变元与复合命题'), '命题逻辑与有效推理_L1_命题、变元与复合命题.md');
assert.equal(md.unitFilename('课程','L1.2.3.12','细化单元'), '课程_L1.2.3.12_细化单元.md');
assert.equal(md.unitFilename('课程','L1/2','单元'), '课程_L未编号_单元.md');
assert.equal(md.unitFilename('',0,''), '学习资料_L未编号_未命名单元.md');
assert.equal(md.unitFilename(' /:*?"<>| ',2,'../概念\n测试'), '学习资料_L2_.. 概念 测试.md');
assert(Buffer.byteLength(md.unitFilename('课'.repeat(100),12,'题'.repeat(100))) < 255);
console.log('PASS notes, formula fallback, safe complete unit filenames');
