'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const listeners = {}, field = {textContent: '', hidden: true};
const env = {document: {readyState: 'loading', body: null, addEventListener(name, fn) {listeners[name] = fn;}, getElementById() {return field;}}};
env.window = env;
vm.createContext(env);
vm.runInContext(fs.readFileSync('shared/ui.js', 'utf8'), env);
const ui = env.LearnUI;
ui.dom.showError('field', '<img src=x onerror=attack()>');
assert.equal(field.textContent, '<img src=x onerror=attack()>');
assert.equal(field.hidden, false);
assert.equal(ui.dom.escapeHTML('<b>"&\'</b>'), '&lt;b&gt;&quot;&amp;&#39;&lt;/b&gt;');
ui.dom.showError('field', '');
assert.equal(field.hidden, true);
let opened = 0, closed = 0, focused = 0, cleaned = 0, cancel;
const dialogEvents = {};
const dialog = {open: false, showModal() {this.open = true; opened++;}, close() {this.open = false; closed++; dialogEvents.close();}, addEventListener(name, fn) {dialogEvents[name] = fn;}};
ui.dialog.bind(dialog, {addEventListener(name, fn) {cancel = fn;}}, () => cleaned++);
ui.dialog.open(dialog, {focus() {focused++;}});
ui.dialog.open(dialog);
assert.equal(opened, 1);
assert.equal(focused, 1);
cancel();
ui.dialog.close(dialog);
assert.equal(closed, 1);
assert.equal(cleaned, 1);
let ready = 0;
ui.dom.ready(() => ready++);
assert.equal(ready, 0);
listeners.DOMContentLoaded();
assert.equal(ready, 1);
console.log('PASS UI Kit text safety, form errors, modal focus/cancel and DOM readiness');
